"""Compile the vla_difficulty_v1 task design into standard scenario YAMLs.

Every variant = base task x language level x spatial level. A variant is
fully determined by (task, L, S) and is composed from

    assets/tasks/vla_difficulty_v1/common.yaml
    assets/tasks/vla_difficulty_v1/base_tasks/<task>.yaml

  instruction = language[L][S] for L1 (location-specific), language[L] otherwise
  objects     = target + background_objects            (identical across L/S)
  placements  = spatial[S].placement + background_placements
  goal        = base task goal                          (identical across L/S)

Output (no new runtime code: the result is an ordinary ScenarioSpec file):

    build/vla_difficulty_v1/<variant_id>/scenario.yaml
    build/vla_difficulty_v1/<variant_id>/variant.json   (L/S metadata, not seen by the agent)
    build/vla_difficulty_v1/manifest.json

Each compiled file is validated with core.scenario.load_scenario.

    python scripts/compile_vla_variants.py                # all variants
    python scripts/compile_vla_variants.py --only T01_knife_fetch__L1_S1
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

from rummagebench.core.scenario import load_scenario

ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / "assets/tasks/vla_difficulty_v1"
OUT = ROOT / "build/vla_difficulty_v1"


def _load(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def instruction_for(task: dict, level_l: str, level_s: str) -> str:
    text = task["language"][level_l]
    if isinstance(text, dict):  # L1 names the location of the current S
        text = text[level_s]
    return " ".join(str(text).split())


def compose(common: dict, task: dict, level_l: str, level_s: str) -> tuple[str, dict, dict]:
    variant_id = f"{task['task_id']}__{level_l}_{level_s}"
    spatial = task["spatial"][level_s]
    target = task["target"]
    robot = dict(common["robot"])
    scenario = {
        "id": variant_id,
        "instruction": instruction_for(task, level_l, level_s),
        "scene": dict(common["scene"]),
        "robot": robot,
        "anchors": dict(common["anchors"]),
        "target": {"entity": target["entity"], "category": target["category"]},
        "objects": [
            {"name": target["entity"], "category": target["category"], "model": target["model"]},
            *[dict(o) for o in task.get("background_objects", [])],
        ],
        "placements": [dict(spatial["placement"]),
                       *[dict(p) for p in task.get("background_placements", [])]],
        "initial_states": dict(task.get("initial_states", {})),
        "termination": dict(common["termination"]),
        "feasibility": dict(common["feasibility"]),
        "skills": list(common["skills"]),
        "expose_available_skills": common.get("expose_available_skills", False),
        "goal": [dict(g) for g in task["goal"]],
    }
    meta = {
        "variant_id": variant_id,
        "task_id": task["task_id"],
        "family": task.get("family"),
        "language_level": level_l,
        "spatial_level": level_s,
        "target_room": spatial.get("room"),
        "location_phrase": spatial.get("location_phrase"),
        "target_placement": spatial["placement"],
        "goal": task["goal"],
        "start_to_target_m": spatial.get("start_to_target_m"),
        "target_to_goal_m": spatial.get("target_to_goal_m"),
        "extra_ops_vs_S1": spatial.get("extra_ops_vs_S1", []),
        "start_anchor": common["robot"]["init_anchor"],
    }
    return variant_id, scenario, meta


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--only", nargs="*", help="variant ids to compile (default: all)")
    p.add_argument("--out", type=Path, default=OUT)
    a = p.parse_args()

    common = _load(DESIGN / "common.yaml")
    index = _load(DESIGN / "variants.yaml")
    manifest = {"design": str(DESIGN.relative_to(ROOT)), "variants": []}
    for task_id in index["tasks"]:
        task = _load(DESIGN / "base_tasks" / f"{task_id}.yaml")
        for level_l in index["language_levels"]:
            for level_s in index["spatial_levels"]:
                variant_id, scenario, meta = compose(common, task, level_l, level_s)
                if a.only and variant_id not in a.only:
                    continue
                vdir = a.out / variant_id
                vdir.mkdir(parents=True, exist_ok=True)
                path = vdir / "scenario.yaml"
                header = (f"# GENERATED by scripts/compile_vla_variants.py from "
                          f"{meta['task_id']} x {level_l} x {level_s}; do not edit.\n")
                path.write_text(header + yaml.safe_dump(scenario, sort_keys=False,
                                                        allow_unicode=True), encoding="utf-8")
                load_scenario(path)  # raises on any schema / cross-check problem
                (vdir / "variant.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n")
                manifest["variants"].append({**meta, "scenario": str(path.relative_to(ROOT))})
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print(f"compiled {len(manifest['variants'])} variants -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
