"""vla_difficulty_v2 -> MOVE_TO protocol: choose each task's start heading.

Since 2026-10-26 the public protocol has no MOVE / TURN; MOVE_TO keeps the
robot's heading for the whole episode, so every interaction (OPEN / GRASP /
PLACE) must be feasible at the START heading. For each physical config that
was accepted under MOVE / TURN, the old route oracle logged the feasible
interaction poses [x, y, yaw] of every subgoal; this script picks the start
yaw that the most subgoals share (within TOL_DEG), preferring the old chosen
GRASP pose's yaw. Position, objects, instructions are unchanged.

Writes build/vla_difficulty_v2_moveto/<variant_id>/{scenario.yaml,variant.json}
for L1/L2/L3 of every such config, and a manifest.json there. The original
build/vla_difficulty_v2 is not modified.

    python scripts/v2/moveto_start_yaw.py
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC_BUILD = ROOT / "build/vla_difficulty_v2"
SRC_RUNS = ROOT / "runs/vla_difficulty_v2"
OUT = ROOT / "build/vla_difficulty_v2_moveto"
TOL_DEG = 20.0


def _wrap(a: float) -> float:
    return (a + math.pi) % (2 * math.pi) - math.pi


def choose_yaw(oracle_log: list[dict]) -> tuple[float | None, dict]:
    per_goal: dict[str, list[float]] = {}
    chosen_grasp = None
    for row in oracle_log:
        if "pose_search" not in row or row.get("protocol") == "MOVE_TO":
            continue
        key = "/".join(row["pose_search"])
        per_goal.setdefault(key, []).extend(p[2] for p in row.get("feasible_poses", []))
        if row["pose_search"][0] == "GRASP" and row.get("chosen"):
            chosen_grasp = row["chosen"]["pose"][2]
    if not per_goal:
        return None, {"reason": "no pose search logged"}
    tol = math.radians(TOL_DEG)
    best = None
    for yaw in sorted({y for ys in per_goal.values() for y in ys}):
        covered = sum(any(abs(_wrap(y - yaw)) <= tol for y in ys) for ys in per_goal.values())
        pref = 0 if chosen_grasp is None else -abs(_wrap(yaw - chosen_grasp))
        cand = (covered, pref, yaw)
        if best is None or cand > best:
            best = cand
    covered, _, yaw = best
    return yaw, {"subgoals": list(per_goal), "covered": covered, "all_covered": covered == len(per_goal)}


def main() -> int:
    manifest = json.loads((SRC_BUILD / "manifest.json").read_text())
    configs = json.loads((SRC_RUNS / "summary.json").read_text())["configs"]
    out_variants, stats = [], {"configs": 0, "all_covered": 0, "partial": 0, "skipped": 0}
    choice: dict[str, tuple] = {}
    for key, c in configs.items():
        if c["status"] != "accepted":
            continue
        report = json.loads((SRC_RUNS / c["variant_id"] / "report.json").read_text())
        yaw, info = choose_yaw(report["scripted_execution"].get("oracle_log", []))
        stats["configs"] += 1
        if yaw is None:
            stats["skipped"] += 1
            continue
        stats["all_covered" if info["all_covered"] else "partial"] += 1
        choice[key] = (yaw, info)
    for v in manifest["variants"]:
        key = f"{v['task_id']}|{v['spatial_level']}"
        if key not in choice:
            continue
        yaw, info = choice[key]
        src = ROOT / v["scenario"]
        scen = yaml.safe_load(src.read_text())
        anchor = scen["anchors"][scen["robot"]["init_anchor"]]
        old_yaw = v["start"]["yaw"]
        anchor["orientation"] = [0.0, 0.0, round(math.sin(yaw / 2), 6), round(math.cos(yaw / 2), 6)]
        dst = OUT / v["variant_id"]
        dst.mkdir(parents=True, exist_ok=True)
        header = (f"# GENERATED by scripts/v2/moveto_start_yaw.py from {v['scenario']}:\n"
                  f"# start yaw {old_yaw:.3f} -> {yaw:.3f} (MOVE_TO keeps the heading); nothing else changed.\n")
        (dst / "scenario.yaml").write_text(header + yaml.safe_dump(scen, sort_keys=False))
        nv = {**v, "start": {**v["start"], "yaw": round(yaw, 3)},
              "scenario": str((dst / "scenario.yaml").relative_to(ROOT)),
              "moveto_start_yaw": {"from": old_yaw, "to": round(yaw, 3), **info}}
        (dst / "variant.json").write_text(json.dumps(nv, indent=1) + "\n")
        out_variants.append(nv)
    design = {"source_design": manifest.get("design"),
              "moveto_note": "start heading re-chosen for the MOVE_TO protocol (scripts/v2/moveto_start_yaw.py)"}
    (OUT / "manifest.json").write_text(json.dumps({"design": design, "variants": out_variants}, indent=1) + "\n")
    print(json.dumps({**stats, "variants": len(out_variants)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
