def destination_objects(layout,room,kind):
    def match(cat):
        if kind=='sink':return cat in ('sink','furniture_sink')
        if kind=='desk':return cat=='desk'
        if kind in ('table','basket'):return cat in {'table','breakfast_table','coffee_table','console_table','dining_table','end_table','folding_table','side_table'}
        if kind=='counter':return 'countertop' in cat or 'bottom_cabinet' in cat
        return 'bottom_cabinet' in cat or 'dresser' in cat or 'nightstand' in cat
    return [n for n,r in layout.entities.items() if room in r.get('in_rooms',[]) and r.get('aabb') and
            match(r['category']) and .35<=r['aabb'][1][2]<=1.25 and
            min(np.subtract(r['aabb'][1],r['aabb'][0])[:2])>.25]


