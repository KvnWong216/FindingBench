            options.sort(key=lambda o:(
                max(g.interior_fit_rank(o[0].entities[o[3]['entity']],data[k]['size']) for k in targetkeys)
                    if o[3]['relation']=='inside' else 0,
                scene_counts[o[0].scene],o[6],o[0].scene,o[3]['entity'],o[5]))
            option=options.pop(0);layout,room,_,src,droom,dest,_=option
            if layout.scene in used:continue
            route=layout.route(src['entity'],room,dest,droom)
